"""Safely unpack paper uploads in memory using standard archive formats."""

from __future__ import annotations

import gzip
import io
import stat
import tarfile
import zipfile
import zlib
from pathlib import PurePosixPath, PureWindowsPath
from typing import BinaryIO

from fastapi import HTTPException

_ARCHIVE_SUFFIXES = (".zip", ".tar.gz", ".tgz", ".tar")


def is_paper_archive(filename: str) -> bool:
    """Return whether a filename names a supported upload archive."""
    return filename.lower().endswith(_ARCHIVE_SUFFIXES)


def safe_archive_path(raw: str, *, directory: bool = False) -> PurePosixPath:
    """Normalize relative paths while rejecting traversal and platform escapes."""
    try:
        raw.encode("utf-8")
    except UnicodeEncodeError as exc:
        raise HTTPException(status_code=400, detail="Archive filenames must use valid Unicode") from exc
    path = PurePosixPath(raw.replace("\\", "/"))
    if (
        "\x00" in raw
        or path.is_absolute()
        or PureWindowsPath(raw).drive
        or ".." in path.parts
        or (not directory and not path.parts)
    ):
        raise HTTPException(status_code=400, detail=f"Archive contains an unsafe path: {raw}")
    return path


def _is_metadata(path: PurePosixPath) -> bool:
    """Ignore files generated by desktop archive utilities."""
    return any(
        part.casefold() in {"__macosx", ".ds_store", "thumbs.db", "desktop.ini"} or part.startswith("._")
        for part in path.parts
    )


def expand_paper_uploads(
    files: list[tuple[str, bytes]],
    *,
    max_upload_bytes: int,
    max_expanded_bytes: int,
    max_files: int,
) -> list[tuple[str, bytes]]:
    """Expand an entire upload batch before any source or storage is changed.

    Args:
        files: Uploaded filenames or browser-relative paths and raw contents.
        max_upload_bytes: Cumulative limit for incoming compressed and loose bytes.
        max_expanded_bytes: Cumulative limit for all extracted and loose contents.
        max_files: Maximum number of retained files across all uploads.

    Returns:
        Normalized relative paths and contents, with archives replaced by members.

    Raises:
        HTTPException: If a batch is unsafe, corrupt, unsupported, or oversized.
    """
    if sum(len(data) for _, data in files) > max_upload_bytes:
        raise HTTPException(status_code=413, detail="Paper source cannot exceed 100 MiB")
    result: list[tuple[str, bytes]] = []
    seen: set[str] = set()
    expanded_bytes = 0
    # Bound headers, padding and ignored metadata before the TAR parser reads them.
    tar_count = sum(is_paper_archive(path) and not path.lower().endswith(".zip") for path, _ in files)
    tar_stream_remaining = max_expanded_bytes + max_files * 4096 + tar_count * tarfile.RECORDSIZE

    class BoundedTarStream:
        """Share a decompression budget across every TAR archive in the batch."""

        def __init__(self, stream: BinaryIO):
            self.stream = stream

        def read(self, size: int = -1) -> bytes:
            """Reject excess decompression before parsing extended headers."""
            nonlocal tar_stream_remaining
            size = tar_stream_remaining + 1 if size < 0 else min(size, tar_stream_remaining + 1)
            data = self.stream.read(size)
            tar_stream_remaining -= len(data)
            if tar_stream_remaining < 0:
                raise HTTPException(status_code=413, detail="Expanded paper archive stream is too large")
            return data

    def add(path: PurePosixPath, size: int, stream: BinaryIO) -> None:
        nonlocal expanded_bytes
        if _is_metadata(path):
            return
        if is_paper_archive(path.name):
            raise HTTPException(status_code=400, detail=f"Nested archive: {path}. Upload it separately.")
        marker = path.as_posix().casefold()
        if marker in seen:
            raise HTTPException(status_code=400, detail=f"Duplicate paper source path: {path}")
        if len(result) >= max_files:
            raise HTTPException(status_code=413, detail="Paper source contains too many files")
        remaining = max_expanded_bytes - expanded_bytes
        if size < 0:
            raise HTTPException(status_code=400, detail=f"Invalid archive member size: {path}")
        if size > remaining:
            raise HTTPException(status_code=413, detail="Expanded paper source is too large")
        data = stream.read(remaining + 1)
        if len(data) > remaining:
            raise HTTPException(status_code=413, detail="Expanded paper source is too large")
        if len(data) != size:
            raise HTTPException(status_code=400, detail=f"Archive member is incomplete: {path}")
        seen.add(marker)
        expanded_bytes += len(data)
        result.append((path.as_posix(), data))

    for raw_path, data in files:
        outer = safe_archive_path(raw_path)
        if _is_metadata(outer):
            continue
        if not is_paper_archive(outer.name):
            add(outer, len(data), io.BytesIO(data))
            continue
        start_count = len(result)
        try:
            if outer.name.lower().endswith(".zip"):
                with zipfile.ZipFile(io.BytesIO(data)) as archive:
                    for entry in archive.infolist():
                        path = safe_archive_path(entry.orig_filename, directory=entry.is_dir())
                        file_type = stat.S_IFMT(entry.external_attr >> 16)
                        if file_type not in {0, stat.S_IFREG, stat.S_IFDIR} or (
                            file_type == stat.S_IFDIR and not entry.is_dir()
                        ):
                            raise HTTPException(
                                status_code=400, detail=f"Archive contains a link or special file: {path}"
                            )
                        if entry.flag_bits & 1:
                            raise HTTPException(status_code=400, detail="Encrypted archives are not supported")
                        if entry.is_dir() or _is_metadata(path):
                            continue
                        with archive.open(entry) as stream:
                            add(outer.parent / path, entry.file_size, stream)
            else:
                compressed = outer.name.lower().endswith((".tar.gz", ".tgz")) or data.startswith(b"\x1f\x8b")
                decoded = gzip.GzipFile(fileobj=io.BytesIO(data)) if compressed else io.BytesIO(data)
                with decoded:
                    bounded = BoundedTarStream(decoded)
                    with tarfile.open(fileobj=bounded, mode="r|", bufsize=tarfile.BLOCKSIZE) as archive:
                        for entry in archive:
                            path = safe_archive_path(entry.name, directory=entry.isdir())
                            if entry.isdir():
                                continue
                            if not entry.isfile():
                                raise HTTPException(
                                    status_code=400, detail=f"Archive contains a link or special file: {path}"
                                )
                            if _is_metadata(path):
                                continue
                            stream = archive.extractfile(entry)
                            if stream is None:
                                raise HTTPException(status_code=400, detail=f"Unreadable archive member: {path}")
                            with stream:
                                add(outer.parent / path, entry.size, stream)
                    # TAR ends before gzip's footer; consume it under the same budget to verify integrity.
                    while bounded.read(64 * 1024):
                        pass
        except (
            zipfile.BadZipFile,
            tarfile.TarError,
            zlib.error,
            OSError,
            EOFError,
            RuntimeError,
            ValueError,
            NotImplementedError,
        ) as exc:
            raise HTTPException(status_code=400, detail=f"Invalid or unsupported paper archive: {outer.name}") from exc
        if len(result) == start_count:
            raise HTTPException(status_code=400, detail=f"Paper archive is empty: {outer.name}")
    return result
