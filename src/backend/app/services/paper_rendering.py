_STYLE_PATH = Path(__file__).resolve().parents[1] / "templates" / "nsfc-proposal.typ"
_STYLE_ENTRY = "styles/nsfc-proposal.typ"
_RENDER_TIMEOUT = 30.0
_ARTIFACT_NAME = re.compile(r"(?P<build>[a-f0-9]{64})\.(?P<extension>pdf|typ)\Z")


@dataclass
class RenderedProposal:
    """In-memory generated bytes and real diagnostics for a source snapshot."""

    status: Literal["ready", "failed"]
    entry_path: str
    diagnostics: list[PaperRenderDiagnostic] = field(default_factory=list)
    typst: bytes | None = None
    pdf: bytes | None = None


def default_markdown_proposal(title: str, description: str | None) -> list[tuple[str, bytes]]:
    """Create the sectioned author draft with the existing editable Typst style.

    Args:
        title: Author-supplied workspace title, preserved verbatim.
        description: Initial author brief, retained by the proposal generator.

    Returns:
        Official chapters, proposal state and log, and the editable Typst style.
    """
    from app.services.paper_proposal import default_sectioned_proposal

    return [*default_sectioned_proposal(title, description), (_STYLE_ENTRY, _STYLE_PATH.read_bytes())]


def _font_paths() -> list[Path]:
    """Find the same bundled static fonts used by the browser preview."""
    configured = os.environ.get("TYPST_FONT_DIR")
    candidates = (
        [Path(configured)]
        if configured
        else [
            Path("/app/typst-fonts"),
            Path(__file__).resolve().parents[3] / "frontend" / "public" / "typst-fonts",
        ]
    )
    return [candidate.resolve() for candidate in candidates if candidate.is_dir()]


def _converter_version() -> str:
    """Read the installed converter identity only when a render is requested."""
    converter = shutil.which("pandoc")
    if converter is None:
        return "pandoc-unavailable"
    try:
        result = subprocess.run([converter, "--version"], capture_output=True, timeout=5, check=True)
        version = result.stdout.decode("utf-8", "replace").splitlines()[0]
        binary_hash = hashlib.sha256(Path(converter).read_bytes()).hexdigest()
        return f"{version}; sha256={binary_hash}"
    except (OSError, subprocess.SubprocessError, IndexError):
        return "pandoc-unavailable"


@lru_cache(maxsize=8)
def _renderer_fingerprint(converter: str, fonts: tuple[str, ...]) -> str:
    """Identify renderer code, compiler, template and the actual bundled fonts."""
    digest = hashlib.sha256(Path(__file__).read_bytes() + _STYLE_PATH.read_bytes() + converter.encode())
    try:
        digest.update(importlib.metadata.version("typst").encode())
    except importlib.metadata.PackageNotFoundError:
        digest.update(b"typst-unavailable")
    for directory in fonts:
        for font in sorted(Path(directory).iterdir()):
            if font.suffix.lower() in {".otf", ".ttf", ".ttc"} and font.is_file():
                digest.update(font.name.encode())
                digest.update(hashlib.sha256(font.read_bytes()).digest())
    return digest.hexdigest()


def _validated_entries(entries: list[tuple[str, bytes]]) -> dict[str, bytes]:
    """Reject resource traversal and duplicate names before creating any files."""
    result = {}
    seen = set()
    if len(entries) > 2_000 or sum(len(data) for _, data in entries) > 500 * 1024 * 1024:
        raise ValueError("Paper render source exceeds the existing source bundle limits")
    for raw, data in entries:
        path = safe_archive_path(raw).as_posix()
        if path.casefold() in seen:
            raise ValueError(f"Duplicate paper resource: {path}")
        seen.add(path.casefold())
        result[path] = data
    for path in result:
        if any(parent.as_posix().casefold() in seen for parent in PurePosixPath(path).parents if parent.parts):
            raise ValueError(f"Conflicting file and directory paths: {path}")
    return result


# This fixed worker code receives data over stdin, never executable author flags.
# A killable process bounds both Pandoc and the native Typst compiler's runtime.
_RENDER_WORKER = r'''
import ctypes
import errno
import json
import os
from pathlib import Path
import re
import subprocess
import sys


def isolate_network():
    """Deny socket operations in this worker and its converter children."""
    if sys.platform != "linux":
        raise RuntimeError("Offline rendering requires the Linux network sandbox")
    library = ctypes.CDLL("libseccomp.so.2", use_errno=True)
    library.seccomp_init.argtypes = [ctypes.c_uint32]
    library.seccomp_init.restype = ctypes.c_void_p
    library.seccomp_syscall_resolve_name.argtypes = [ctypes.c_char_p]
    library.seccomp_syscall_resolve_name.restype = ctypes.c_int
    library.seccomp_rule_add.argtypes = [ctypes.c_void_p, ctypes.c_uint32, ctypes.c_int, ctypes.c_uint]
    library.seccomp_load.argtypes = [ctypes.c_void_p]
    library.seccomp_release.argtypes = [ctypes.c_void_p]
    context = library.seccomp_init(0x7FFF0000)
    if not context:
        raise RuntimeError("Cannot initialize offline rendering sandbox")
    try:
        for name in (b"socket", b"connect", b"sendto", b"sendmsg", b"sendmmsg"):
            syscall = library.seccomp_syscall_resolve_name(name)
            if syscall >= 0 and library.seccomp_rule_add(context, 0x00050000 | errno.EPERM, syscall, 0) != 0:
                raise RuntimeError("Cannot restrict render networking")
        if library.seccomp_load(context) != 0:
            raise RuntimeError("Cannot activate offline rendering sandbox")
    finally:
        library.seccomp_release(context)


def diagnostic(message, severity="error", path=None):
    """Keep converter diagnostics relative to source, without temporary paths."""
    message = str(message).replace(str(root) + os.sep, "")
    value = {"message": message, "severity": severity, "path": path or job["entry"]}
    location = re.search(r"(?:\.typ|\.md):(\d+)(?::\d+)?", message)
    if location:
        value["line"] = int(location.group(1))
    return value


job = json.load(sys.stdin)
root = Path(job["root"])
entry = root / job["entry"]
output = Path(job["output"])
result = {"status": "failed", "diagnostics": []}
try:
    isolate_network()
    import typst
    if entry.suffix.lower() in {".md", ".markdown"}:
        if not job["pandoc"]:
            raise RuntimeError("Pandoc is unavailable; install the pinned converter in the build image")
        process = subprocess.run(
            [job["pandoc"], "--sandbox", "--from=markdown-raw_html-raw_tex-raw_attribute",
             "--to=typst", "--wrap=none", "--data-dir=" + job["state"],
             "--log=" + str(Path(job["state"]) / "conversion.json"), "--",
             *[str(root / path) for path in job["entries"]]],
            cwd=entry.parent, capture_output=True, timeout=job["timeout"], check=False,
        )
        stderr = process.stderr.decode("utf-8", "replace").strip()
        if process.returncode:
            raise RuntimeError("Markdown conversion failed: " + stderr)
        conversion_log = Path(job["state"]) / "conversion.json"
        messages = json.loads(conversion_log.read_text()) if conversion_log.exists() else []
        unsupported = [item for item in messages if item.get("type") == "CouldNotConvertTeXMath"]
        if unsupported:
            raise RuntimeError("Math conversion failed; the Markdown source is unchanged: " +
                               "\n".join(item.get("pretty", item.get("message", "")) for item in unsupported))
        if stderr:
            result["diagnostics"].append(diagnostic(stderr, "warning"))
        # Pandoc owns Markdown conversion. The wrapper only selects editable styling.
        wrapper = ('#import "/styles/nsfc-proposal.typ": nsfc-proposal\n'
                   '#show: nsfc-proposal.with(title: "报告正文")\n\n').replace("\\n", "\n")
        generated = wrapper.encode("utf-8") + process.stdout
        bibliography = root / "references.bib"
        if job["legacy_bibliography"] and bibliography.exists() and any(
            line.strip() and not line.lstrip().startswith("%")
            for line in bibliography.read_text(encoding="utf-8").splitlines()
        ):
            generated += b'\n#bibliography("/references.bib")\n'.replace(b"\\n", b"\n")
        # Keep images relative to the entry while the compiler root stays isolated.
        compile_entry = entry.parent / job["generated_name"]
        compile_entry.write_bytes(generated)
    else:
        generated = entry.read_bytes()
        compile_entry = entry
    (output / "proposal.typ").write_bytes(generated)
    pdf, warnings = typst.compile_with_warnings(
        str(compile_entry), root=str(root), font_paths=job["fonts"], ignore_system_fonts=True,
    )
    for warning in warnings:
        result["diagnostics"].append(diagnostic(getattr(warning, "message", str(warning)), "warning"))
    (output / "proposal.pdf").write_bytes(pdf)
    result["status"] = "ready"
except Exception as exc:
    trace = getattr(exc, "trace", None)
    result["diagnostics"].append(diagnostic(str(exc) + ("\n" + str(trace) if trace else "")))
print(json.dumps(result, ensure_ascii=False))
'''


def render_proposal(
    entries: list[tuple[str, bytes]],
    entry_path: str | None = None,
    *,
    entry_paths: list[str] | None = None,
    timeout_seconds: float = _RENDER_TIMEOUT,
) -> RenderedProposal:
    """Convert an immutable source snapshot into in-memory Typst and PDF bytes.

    Args:
        entries: Relative resource paths and source bytes; never modified in place.
        entry_path: Markdown or legacy Typst entry within the resource tree.
        entry_paths: Ordered Markdown inputs, overriding the single entry default.
        timeout_seconds: Wall-clock bound for conversion and native compilation.

    Returns:
        Generated bytes and actual diagnostics, including partial Typst on failure.
    """
    from app.services.paper_proposal import proposal_entry_paths

    result = RenderedProposal(status="failed", entry_path=entry_path or "proposal.md")
    try:
        resources = _validated_entries(entries)
        section_paths = proposal_entry_paths(entries)
        selected = entry_paths
        if selected is None:
            selected = (
                [entry_path] if entry_path is not None else section_paths or [_entry_for_source(entries, None, None)]
            )
        selected = _validated_selection(resources, selected)
        entry_path = selected[0]
        result.entry_path = entry_path
        legacy_bibliography = len(selected) == 1 and not section_paths
        fonts = _font_paths()
        if not fonts:
            raise ValueError("Bundled Typst fonts are unavailable; build the verified frontend font cache")
        with tempfile.TemporaryDirectory(prefix="llm4ad-paper-render-") as temporary:
            directory = Path(temporary)
            root, output, state = directory / "source", directory / "build", directory / "state"
            for path in (root, output, state):
                path.mkdir()
            for relative, content in resources.items():
                target = root / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(content)
            if _STYLE_ENTRY not in resources:
                target = root / _STYLE_ENTRY
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(_STYLE_PATH.read_bytes())
            job = {
                "root": str(root),
                "entry": entry_path,
                "entries": selected,
                "legacy_bibliography": legacy_bibliography,
                "output": str(output),
                "state": str(state),
                "pandoc": shutil.which("pandoc"),
                "fonts": [str(path) for path in fonts],
                "timeout": timeout_seconds,
                "generated_name": f".render-{os.urandom(12).hex()}.typ",
            }
            environment = {
                "PATH": os.defpath,
                "HOME": str(state),
                "XDG_CACHE_HOME": str(state),
                "XDG_DATA_HOME": str(state),
                "TMPDIR": str(state),
                "LANG": "C.UTF-8",
                "LC_ALL": "C.UTF-8",
                "SOURCE_DATE_EPOCH": "0",
            }
            process = subprocess.Popen(
                [sys.executable, "-I", "-c", _RENDER_WORKER],
                cwd=root,
                env=environment,
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                start_new_session=os.name == "posix",
            )
            timed_out = False
            try:
                stdout, stderr = process.communicate(json.dumps(job).encode(), timeout=timeout_seconds)
            except subprocess.TimeoutExpired:
                timed_out = True
                try:
                    if os.name == "posix":
                        os.killpg(process.pid, signal.SIGKILL)
                    else:
                        process.kill()
                except ProcessLookupError:
                    pass
                stdout, stderr = process.communicate()
            for name, attribute in (("proposal.typ", "typst"), ("proposal.pdf", "pdf")):
                target = output / name
                if target.is_file():
                    setattr(result, attribute, target.read_bytes())
            if timed_out:
                raise TimeoutError("Proposal rendering exceeded its time limit")
            if process.returncode:
                message = stderr.decode("utf-8", "replace").replace(str(directory), "[render]")
                raise RuntimeError(f"Render worker failed: {message or process.returncode}")
            payload = json.loads(stdout)
            result.status = payload["status"]
            result.diagnostics = [PaperRenderDiagnostic.model_validate(item) for item in payload["diagnostics"]]
    except (HTTPException, ValueError, OSError, RuntimeError, TimeoutError) as exc:
        message = str(exc.detail) if isinstance(exc, HTTPException) else str(exc)
        result.diagnostics.append(PaperRenderDiagnostic(message=message, path=result.entry_path))
    return result


def _render_prefix(user_id: uuid.UUID, workspace_id: uuid.UUID, source: models.PaperSourceVersion) -> str:
    """Scope immutable builds to an owned source revision and its content hash."""
    return f"paper/{user_id}/{workspace_id}/renders/{source.id}/{source.content_hash}"


def _stored_render(storage, prefix: str) -> PaperRenderResponse | None:
    """Read a completed build manifest while distinguishing absent objects."""
    from botocore.exceptions import ClientError

    try:
        return PaperRenderResponse.model_validate_json(storage.download(f"{prefix}/manifest.json"))
    except KeyError:
        return None
    except ClientError as exc:
        error = exc.response.get("Error", {}).get("Code", "")
        if str(error) in {"404", "NoSuchKey", "NotFound"}:
            return None
        raise
    except ValueError:
        return None


def _entry_for_source(entries: list[tuple[str, bytes]], requested: str | None, preferred: str | None) -> str:
    """Resolve a default entry while keeping explicitly requested paths exact."""
    if requested is not None:
        return requested
    paths = {path for path, _ in entries}
    for candidate in ("proposal.md", preferred, "proposal.typ", "main.typ"):
        if candidate and candidate in paths and PurePosixPath(candidate).suffix.lower() in {".md", ".markdown", ".typ"}:
            return candidate
    candidates = sorted(path for path in paths if PurePosixPath(path).suffix.lower() in {".md", ".markdown", ".typ"})
    return candidates[0] if candidates else "proposal.md"


def _validated_selection(resources: dict[str, bytes], selected: list[str]) -> list[str]:
    """Check only input existence, safe paths, uniqueness and supported formats."""
    if not selected:
        raise ValueError("At least one render entry is required")
    normalized = [safe_archive_path(path).as_posix() for path in selected]
    if len({path.casefold() for path in normalized}) != len(normalized):
        raise ValueError("Render entries must not contain duplicate paths")
    for path in normalized:
        if path not in resources:
            raise ValueError(f"Render entry was not found: {path}")
        suffix = PurePosixPath(path).suffix.lower()
        if suffix not in {".md", ".markdown", ".typ"}:
            raise ValueError("Render entry must be Markdown or Typst")
        if len(normalized) > 1 and suffix == ".typ":
            raise ValueError("Multiple render entries must all be Markdown")
    return normalized


def _entries_for_source(
    entries: list[tuple[str, bytes]],
    requested: str | None,
    requested_paths: list[str] | None,
    preferred: str | None,
) -> list[str]:
    """Resolve explicit input order or the parent's canonical section order."""
    from app.services.paper_proposal import proposal_entry_paths

    selected = requested_paths
    if selected is None:
        selected = [requested] if requested is not None else proposal_entry_paths(entries)
        selected = selected or [_entry_for_source(entries, None, preferred)]
    try:
        selected = _validated_selection(_validated_entries(entries), selected)
        if requested is not None and safe_archive_path(requested).as_posix() != selected[0]:
            raise ValueError("entry_path must match the first entry_paths input")
    except (ValueError, HTTPException) as exc:
        detail = exc.detail if isinstance(exc, HTTPException) else str(exc)
        raise HTTPException(status_code=422, detail=detail) from exc
    return selected


def _selection_hash(selected: list[str]) -> str:
    """Identify the exact ordered inputs independently of converter discovery."""
    return hashlib.sha256(json.dumps(selected, ensure_ascii=False).encode()).hexdigest()


def _selection_prefix(source_prefix: str, selected: list[str]) -> str:
    """Locate the latest persisted result for an ordered source selection."""
    return f"{source_prefix}/selections/{_selection_hash(selected)}"


def _matching_render(
    stored: PaperRenderResponse | None, source: models.PaperSourceVersion, selected: list[str]
) -> bool:
    """Require the exact source and ordered inputs, including legacy manifests."""
    return (
        stored is not None
        and stored.source_version_id == source.id
        and stored.source_hash == source.content_hash
        and (stored.entry_paths or [stored.entry_path]) == selected
        and stored.entry_path == selected[0]
    )


def _remember_render(storage, source_prefix: str, selected: list[str], response: PaperRenderResponse) -> None:
    """Keep a small read-only lookup manifest for ready and failed POST results."""
    storage.upload(
        f"{_selection_prefix(source_prefix, selected)}/manifest.json",
        response.model_dump_json().encode(),
        content_type="application/json",
    )


def get_source_version_render(
    db: Session,
    current_user: models.User,
    source_version_id: uuid.UUID,
    *,
    entry_path: str | None = None,
    entry_paths: list[str] | None = None,
) -> PaperRenderResponse | None:
    """Read a matching stored result without running tools or writing history.

    Args:
        db: Session authorizing the exact source revision and its workspace.
        current_user: Authenticated source owner.
        source_version_id: Current or historical immutable source revision.
        entry_path: Legacy explicit single input.
        entry_paths: Optional ordered Markdown inputs to match.

    Returns:
        A persisted ready or failed result, or None when no match exists.
    """
    from app.services import paper_service

    workspace, source = paper_service._owned_source_version(db, current_user.id, source_version_id)
    selected = _entries_for_source(
        paper_service._source_entries(source), entry_path, entry_paths, workspace.proposal_entry_path or source.filename
    )
    storage = paper_service._storage()
    source_prefix = _render_prefix(current_user.id, workspace.id, source)
    stored = _stored_render(storage, _selection_prefix(source_prefix, selected))
    if _matching_render(stored, source, selected):
        return stored
    references = ((workspace.rebuttal_context or {}).get("_paper_exports") or {}).get(str(source.id), [])
    for key in reversed(references):
        if (
            not key.startswith(source_prefix + "/")
            or not key.endswith("/manifest.json")
            or not re.fullmatch(r"[a-f0-9]{64}", key.removesuffix("/manifest.json").rsplit("/", 1)[-1])
            or ".." in PurePosixPath(key).parts
        ):
            continue
        stored = _stored_render(storage, key.removesuffix("/manifest.json"))
        if _matching_render(stored, source, selected):
            return stored
    return None


def _register_export(
    db: Session, workspace: models.PaperWorkspace, source: models.PaperSourceVersion, prefix: str
) -> None:
    """Index immutable build references while keeping historical source state intact."""
    from sqlmodel import select

    from app import models
    from app.services import paper_revision_history

    workspace = db.exec(
        select(models.PaperWorkspace)
        .where(models.PaperWorkspace.id == workspace.id)
        .with_for_update()
        .execution_options(populate_existing=True)
    ).one()
    manifest_key = f"{prefix}/manifest.json"
    if manifest_key in ((workspace.rebuttal_context or {}).get("_paper_exports") or {}).get(str(source.id), []):
        return
    paper_revision_history.record_export(db, workspace, manifest_key, commit=False)
    if workspace.active_source_version_id == source.id:
        paper_revision_history.capture_revision(
            db,
            workspace,
            origin="export",
            summary="Rendered proposal Typst and PDF",
            commit=False,
        )
    db.commit()


def render_source_version(
    db: Session,
    current_user: models.User,
    source_version_id: uuid.UUID,
    *,
    entry_path: str | None = None,
    entry_paths: list[str] | None = None,
    expected_source_hash: str | None = None,
) -> PaperRenderResponse:
    """Persist derived build outputs without altering a source version.

    Args:
        db: Database session used only to authorize and read the source revision.
        current_user: Authenticated artifact owner.
        source_version_id: Exact current or historical immutable source revision.
        entry_path: Optional explicit Markdown or Typst entry path.
        entry_paths: Optional explicit ordered Markdown inputs.
        expected_source_hash: Author-observed source hash checked before conversion.

    Returns:
        Owner-authenticated artifact URLs and real build diagnostics.
    """
    from app.services import paper_service

    workspace, source = paper_service._owned_source_version(db, current_user.id, source_version_id)
    if expected_source_hash is not None and expected_source_hash != source.content_hash:
        raise HTTPException(status_code=409, detail="Paper source changed; confirm the current source before rendering")
    entries = paper_service._source_entries(source)
    selected = _entries_for_source(entries, entry_path, entry_paths, workspace.proposal_entry_path or source.filename)
    fingerprint = _renderer_fingerprint(_converter_version(), tuple(str(path) for path in _font_paths()))
    build_hash = hashlib.sha256(
        f"{source.content_hash}\0{fingerprint}\0{_selection_hash(selected)}".encode()
    ).hexdigest()
    source_prefix = _render_prefix(current_user.id, workspace.id, source)
    prefix = f"{source_prefix}/{build_hash}"
    storage = paper_service._storage()
    stored = _stored_render(storage, prefix)
    if stored is not None and stored.status == "ready" and _matching_render(stored, source, selected):
        _remember_render(storage, source_prefix, selected, stored)
        _register_export(db, workspace, source, prefix)
        return stored
    rendered = render_proposal(entries, selected[0], entry_paths=selected)
    response = PaperRenderResponse(
        status=rendered.status,
        source_version_id=source.id,
        source_hash=source.content_hash,
        entry_path=selected[0],
        entry_paths=selected,
        diagnostics=rendered.diagnostics,
    )
    route = f"{paper_service.settings.API_V1_STR}/llm4ad/papers/source-versions/{source.id}/render"
    for extension, content, mime_type in (
        ("typ", rendered.typst, "text/plain"),
        ("pdf", rendered.pdf, "application/pdf"),
    ):
        if content is None:
            continue
        filename = f"proposal.{extension}"
        storage.upload(f"{prefix}/{filename}", content, content_type=mime_type)
        url = f"{route}/{build_hash}.{extension}"
        response.files.append(PaperRenderFile(path=filename, mime_type=mime_type, url=url))
        if extension == "pdf":
            response.pdf_url = url
        else:
            response.typst_url = url
    storage.upload(f"{prefix}/manifest.json", response.model_dump_json().encode(), content_type="application/json")
    _remember_render(storage, source_prefix, selected, response)
    if response.status == "ready":
        _register_export(db, workspace, source, prefix)
    return response


def rendered_source_file(db: Session, current_user: models.User, source_version_id: uuid.UUID, filename: str):
    """Authorize an immutable generated artifact and return its streaming body."""
    from app.services import paper_service

    workspace, source = paper_service._owned_source_version(db, current_user.id, source_version_id)
    match = _ARTIFACT_NAME.fullmatch(filename)
    if match is None:
        raise HTTPException(status_code=404, detail="Rendered paper file not found")
    prefix = f"{_render_prefix(current_user.id, workspace.id, source)}/{match['build']}"
    storage = paper_service._storage()
    manifest = _stored_render(storage, prefix)
    artifact = f"proposal.{match['extension']}"
    if (
        manifest is None
        or manifest.source_version_id != source.id
        or manifest.source_hash != source.content_hash
        or not any(item.path == artifact for item in manifest.files)
    ):
        raise HTTPException(status_code=404, detail="Rendered paper file not found")
    return storage.iter_download(f"{prefix}/{artifact}"), "application/pdf" if match[
        "extension"
    ] == "pdf" else "text/plain"
